CREATE TABLE customers(id INTEGER PRIMARY KEY, name VARCHAR(80) NOT NULL, city VARCHAR(80));
CREATE TABLE products(id INTEGER PRIMARY KEY, name VARCHAR(80) NOT NULL, price NUMERIC(10,2) NOT NULL CHECK(price>=0));
CREATE TABLE orders(id INTEGER PRIMARY KEY, customer_id INTEGER REFERENCES customers(id), status VARCHAR(40) NOT NULL);
CREATE TABLE order_items(order_id INTEGER REFERENCES orders(id), product_id INTEGER REFERENCES products(id), quantity INTEGER NOT NULL CHECK(quantity>0), PRIMARY KEY(order_id,product_id));
